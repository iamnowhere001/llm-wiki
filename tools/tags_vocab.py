def clean(tags):
    """过滤移除集并去重，保持原顺序。"""
    out = []
    for t in tags:
        if t in REMOVE or t in out:
            continue
        out.append(t)
    return out


def sort_key(tag, freq):
    """顶栏顺序：系列在前，其后按全库频次降序，同频按字典序。"""
    return (0 if tag in SERIES else 1, -freq.get(tag, 0), tag)
