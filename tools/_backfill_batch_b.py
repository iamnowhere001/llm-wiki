def anchor_pos(text):
    for pat in (r'^## 待办 / 开放问题\s*$', r'^## 开放问题\s*$', r'^## 来源\s*$'):
        m = re.search(pat, text, re.M)
        if m:
            return m.start(), pat
    return None, None


def main():
    dry = '--write' not in sys.argv
    for rel, body in BODY.items():
        p = os.path.join(ROOT, rel)
        if not os.path.exists(p):
            print('NOTFOUND  ', rel); continue
        text = open(p, encoding='utf-8').read()
        if SEC in text:
            print('SKIP-DUP  ', rel); continue
        pos, pat = anchor_pos(text)
        if pos is None:
            print('NOANCHOR  ', rel); continue
        new = text[:pos].rstrip('\n') + '\n\n' + body.strip('\n') + '\n\n' + text[pos:]
        new = re.sub(r'^updated: .*$', 'updated: %s' % DATE, new, count=1, flags=re.M)
        if dry:
            print('DRY  %-44s anchor=待办/开放问题 +%d 字' % (rel.split('/')[-1], len(body)))
